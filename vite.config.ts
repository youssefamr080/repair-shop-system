import { defineConfig, loadEnv } from 'vite'
import path from 'node:path'
import fs from 'node:fs/promises'
import electron from 'vite-plugin-electron/simple'
import react from '@vitejs/plugin-react'
import bytenode from 'bytenode'

// https://vitejs.dev/config/
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '')

  return {
    plugins: [
      react(),
      electron({
        main: {
          // Shortcut of `build.lib.entry`.
          entry: 'electron/main.ts',
          vite: {
            define: {
              // Secrets removed for security (See SecretGuard)
            },
            build: {
              lib: {
                entry: 'electron/main.ts',
                formats: ['cjs'],
                fileName: () => 'main.cjs',
              },
              rollupOptions: {
                external: ['better-sqlite3-multiple-ciphers', 'electron', 'keytar'],
                output: {
                  format: 'cjs',
                  entryFileNames: '[name].cjs',
                  inlineDynamicImports: true,
                },
              },
              // 🛠️ CONDITIONAL: Only watch in dev, not in production build
              watch: mode === 'production' ? null : {
                exclude: ['dist-electron/**', 'release/**', 'logs/**', '**/*.log'],
              },
            },
            plugins: [
              // 🛡️ SECURITY: V8 Bytecode Compilation (Phase 1)
              {
                name: 'bytecode-compiler',
                apply: 'build',
                closeBundle: async () => {
                  if (mode !== 'production') return; // Only compile in production

                  console.log('🔒 [Security] Compiling Main Process to V8 Bytecode...');
                  const distDir = path.join(process.cwd(), 'dist-electron');
                  const mainCjs = path.join(distDir, 'main.cjs');
                  const mainJsc = path.join(distDir, 'main.jsc');

                  try {
                    // 1. Compile main.cjs -> main.jsc
                    await bytenode.compileFile({
                      filename: mainCjs,
                      output: mainJsc,
                    });

                    // 2. Overwrite main.cjs with Loader Script (CJS)
                    const loaderCode = `
// 🛡️ V8 Bytecode Loader
// Generated by Security Hardening Phase 1
"use strict";
require('bytenode');
require('./main.jsc');
`;
                    await fs.writeFile(mainCjs, loaderCode);
                    console.log('✅ [Security] Main Process Bytecode Compilation Complete!');
                  } catch (err) {
                    console.error('❌ [Security] Main Compilation Failed:', err);
                  }
                }
              }
            ],
          },
        },
        preload: {
          // Shortcut of `build.rollupOptions.input`.
          // Preload scripts may contain Web assets, so use the `build.rollupOptions.input` instead `build.lib.entry`.
          input: path.join(__dirname, 'electron/preload.ts'),
          vite: {
            build: {
              sourcemap: 'inline',
              minify: false,
              outDir: 'dist-electron',
              rollupOptions: {
                output: {
                  format: 'cjs',
                  entryFileNames: 'preload.cjs',
                  inlineDynamicImports: true,
                },
              },
            },
            plugins: [
              {
                name: 'bytecode-compiler-preload',
                apply: 'build',
                closeBundle: async () => {
                  if (mode !== 'production') return;

                  console.log('🔒 [Security] Compiling Preload script to V8 Bytecode...');
                  const distDir = path.join(process.cwd(), 'dist-electron');
                  const preloadJs = path.join(distDir, 'preload.cjs');
                  const preloadJsc = path.join(distDir, 'preload.jsc');

                  try {
                    await bytenode.compileFile({
                      filename: preloadJs,
                      output: preloadJsc,
                      compileAsModule: true
                    });

                    const preloadLoader = `
// 🛡️ V8 Bytecode Loader
// Generated by Security Hardening Phase 1
"use strict";
require('bytenode');
require('./preload.jsc');
`;
                    await fs.writeFile(preloadJs, preloadLoader);
                    console.log('✅ [Security] Preload Script Compiled Successfully!');
                  } catch (err) {
                    console.error('❌ [Security] Preload Compilation Failed:', err);
                  }
                }
              }
            ]
          },
        },
        // Polyfill the Electron and Node.js API for Renderer process.
        // If you want use Node.js in Renderer process, the `nodeIntegration` needs to be enabled in the Main process.
        // See 👉 https://github.com/electron-vite/vite-plugin-electron-renderer
        renderer: process.env.NODE_ENV === 'test'
          // https://github.com/electron-vite/vite-plugin-electron-renderer/issues/78#issuecomment-2053600808
          ? undefined
          : {},
      }),

    ],
  }
})
